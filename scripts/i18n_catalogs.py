"""Validate UTF-8 catalogs; generate the embedded English fallback (stdlib only)."""
from pathlib import Path
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CODES = 'pt-BR en-US es-ES fr-FR de-DE it-IT pt-PT nl-NL pl-PL ru-RU ja-JP zh-CN zh-TW ko-KR tr-TR ar-SA hi-IN sv-SE'.split()
CATEGORIES = 'zero one two few many other'.split()

def load(path):
    data = {}
    raw = path.read_bytes()
    assert len(raw) <= 1024 * 1024, path
    text = raw.decode('utf-8-sig', errors='strict')
    for number, line in enumerate(text.splitlines(), 1):
        if not line or line.startswith('#'):
            continue
        key, sep, value = line.partition('\t')
        assert sep and re.fullmatch(r'[a-z0-9_.-]+', key), (path, number)
        assert key not in data and value.strip(), (path, key)
        assert not re.search(r'[\x00-\x1f\x7f\ufeff]', value), (path, key)
        assert not re.search(r'\\(?![n\\])', value), (path, key, 'escape')
        stripped = re.sub(r'\{[a-z0-9_.-]+\}', '', value)
        assert '{' not in stripped and '}' not in stripped, (path, key, 'placeholder')
        data[key] = value
    assert data, path
    return data

def literals():
    # Remove comments while preserving quoted strings (comment markers may be string data).
    token = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|L"(?:\\.|[^"\\])*"|"(?:\\.|[^"\\])*"')
    for path in sorted((ROOT / 'src').glob('*.cpp')):
        for match in token.finditer(path.read_text(encoding='utf-8')):
            if match[0].startswith('L"'):
                yield path.relative_to(ROOT).as_posix(), match[0]

def validate_source(reference):
    exceptions = json.loads((ROOT / 'docs/I18N-LITERAL-EXCEPTIONS.json').read_text(encoding='utf-8'))
    allowed = {(e['file'], e['literal']) for e in exceptions if e['reason']}
    unexpected = set(literals()) - allowed
    assert not unexpected, ('Unclassified wide literals', sorted(unexpected))
    # Every direct call and semantic-ID array must refer to a real message/family.
    used = set()
    for path in (ROOT / 'src').glob('*.cpp'):
        source = path.read_text(encoding='utf-8')
        used.update(re.findall(r'I18n::(?:Text|Format)\("([a-z0-9_.-]+)"\s*[,)]', source))
        used.update(key for key in re.findall(r'(?<!L)"((?:player|audio|playlist|errors|appearance|info|common|equalizer|preset|themes|window|tooltip)\.[a-z0-9_.-]+)"', source) if not key.endswith('.h'))
        for family in re.findall(r'I18n::Count\("([a-z0-9_.-]+)"', source):
            used.update(family+'.'+cat for cat in CATEGORIES)
            used.discard(family)
    theme_source = (ROOT/'src/ui_theme.cpp').read_text(encoding='utf-8')
    used.update('theme.'+key for key in re.findall(r'(?:Make\(|^\s*\{)L"([a-z0-9-]+)"', theme_source, re.M))
    assert used <= reference.keys(), ('Unknown IDs', used-reference.keys())
    assert reference.keys() <= used, ('Unreferenced inventory IDs', reference.keys()-used)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--generate', action='store_true')
    parser.add_argument('--source', action='store_true')
    args = parser.parse_args()
    catalogs = {code: load(ROOT/'locales'/code/'messages.tsv') for code in CODES}
    reference = catalogs['en-US']
    for code, catalog in catalogs.items():
        assert catalog.keys() == reference.keys(), code
        for key, value in catalog.items():
            assert sorted(re.findall(r'\{[^}]+\}', value)) == sorted(re.findall(r'\{[^}]+\}', reference[key])), (code, key)
            if key.endswith('.other'):
                assert all(key[:-6]+'.'+c in catalog for c in CATEGORIES), (code, key)
        print(f'{code}: {len(catalog)}/{len(reference)} keys PASS; {sum(v != reference[k] for k,v in catalog.items())} differ from English (informational)')
    embedded = '// Generated by scripts/i18n_catalogs.py --generate. Do not edit.\n#pragma once\nnamespace I18n {\ninline constexpr char EnglishCatalog[] = u8R"CATALOG(\n'+''.join(k+'\t'+v+'\n' for k,v in sorted(reference.items()))+')CATALOG";\n}\n'
    header = ROOT/'src/i18n_english.h'
    if args.generate:
        header.write_text(embedded, encoding='utf-8')
    else:
        assert header.read_text(encoding='utf-8') == embedded, 'Stale embedded English; run --generate'
    inventory = json.loads((ROOT/'docs/I18N-STRING-INVENTORY.json').read_text(encoding='utf-8'))
    assert {e['id'] for e in inventory} == reference.keys(), 'Inventory coverage'
    if args.source:
        validate_source(reference)
        print('Source literals and IDs PASS')

if __name__ == '__main__':
    try:
        main()
    except (AssertionError, UnicodeError, ValueError, OSError) as error:
        sys.exit(str(error) or 'Catalog validation failed')
